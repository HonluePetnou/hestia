"""SQLAlchemy models (PROJECT_SPEC §4)."""

import enum
from datetime import datetime
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    ARRAY,
    Computed,
    DateTime,
    Enum,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

from app.config import get_settings

EMBEDDING_DIM = get_settings().embedding_dim


class Base(DeclarativeBase):
    pass


class Gravity(enum.StrEnum):
    microgravity = "microgravity"
    lunar = "lunar"
    martian = "martian"
    earth = "earth"


class Outcome(enum.StrEnum):
    spread = "spread"
    extinction = "extinction"
    disruption = "disruption"
    complete_burn = "complete_burn"
    unknown = "unknown"


def _pg_enum(cls: type[enum.Enum], name: str) -> Enum:
    return Enum(cls, name=name, values_callable=lambda e: [m.value for m in e])


SOURCE_NTRS = "ntrs"
SOURCE_PSI = "psi"
SOURCE_RESOURCE = "nasa_resource"
SOURCE_TYPES = (SOURCE_NTRS, SOURCE_PSI, SOURCE_RESOURCE)


class Document(Base):
    """One citable source: an NTRS report, a PSI investigation or another NASA resource.

    `(source_type, external_id)` is the real identity. `ntrs_id` is kept (nullable, unique)
    for backward compatibility and is only filled for NTRS reports.
    """

    __tablename__ = "documents"
    __table_args__ = (
        UniqueConstraint("source_type", "external_id", name="uq_documents_source_external"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    source_type: Mapped[str] = mapped_column(String(16), default=SOURCE_NTRS, server_default="ntrs")
    external_id: Mapped[str] = mapped_column(String(64))
    ntrs_id: Mapped[str | None] = mapped_column(String(32), unique=True, index=True)
    title: Mapped[str] = mapped_column(Text)
    authors: Mapped[list[str]] = mapped_column(ARRAY(Text), default=list)
    year: Mapped[int | None] = mapped_column(Integer)
    url: Mapped[str | None] = mapped_column(Text)
    doi: Mapped[str | None] = mapped_column(Text)
    pdf_path: Mapped[str | None] = mapped_column(Text)
    pdf_url: Mapped[str | None] = mapped_column(Text)
    text_path: Mapped[str | None] = mapped_column(Text)
    meta: Mapped[dict[str, Any]] = mapped_column(JSONB, default=dict, server_default="{}")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    chunks: Mapped[list["Chunk"]] = relationship(back_populates="document")

    def page_url(self, page: int | None = None) -> str | None:
        """Best link for a citation: the PDF at `page`, else the record page, else the DOI."""
        if self.source_type == SOURCE_NTRS:
            if self.pdf_url and page:
                return f"{self.pdf_url}#page={page}"
            return self.url or f"https://ntrs.nasa.gov/citations/{self.external_id}"
        if self.url:
            if page and self.url.lower().endswith(".pdf"):
                return f"{self.url}#page={page}"
            return self.url
        return f"https://doi.org/{self.doi}" if self.doi else None


class Chunk(Base):
    __tablename__ = "chunks"
    __table_args__ = (UniqueConstraint("document_id", "chunk_key", name="uq_chunks_doc_key"),)

    id: Mapped[int] = mapped_column(primary_key=True)
    document_id: Mapped[int] = mapped_column(ForeignKey("documents.id", ondelete="CASCADE"))
    page: Mapped[int | None] = mapped_column(Integer)
    chunk_index: Mapped[int] = mapped_column(Integer)
    chunk_key: Mapped[str] = mapped_column(String(128))
    content: Mapped[str] = mapped_column(Text)
    # Generated by Postgres (migration 0005): to_tsvector('english', content), GIN-indexed.
    content_tsv: Mapped[Any] = mapped_column(
        TSVECTOR, Computed("to_tsvector('english', content)", persisted=True), deferred=True
    )
    content_hash: Mapped[str | None] = mapped_column(String(64))
    embedding: Mapped[list[float] | None] = mapped_column(Vector(EMBEDDING_DIM))
    embedding_model: Mapped[str | None] = mapped_column(String(96))
    token_count: Mapped[int | None] = mapped_column(Integer)
    meta: Mapped[dict[str, Any]] = mapped_column(JSONB, default=dict, server_default="{}")

    document: Mapped[Document] = relationship(back_populates="chunks")


class Experiment(Base):
    __tablename__ = "experiments"

    id: Mapped[int] = mapped_column(primary_key=True)
    code: Mapped[str] = mapped_column(String(32), unique=True, index=True)
    name: Mapped[str] = mapped_column(Text)
    platform: Mapped[str | None] = mapped_column(Text)
    description: Mapped[str | None] = mapped_column(Text)
    objectives: Mapped[str | None] = mapped_column(Text)
    psi_doi: Mapped[str | None] = mapped_column(Text)
    years: Mapped[str | None] = mapped_column(Text)
    fuels: Mapped[str | None] = mapped_column(Text)

    test_runs: Mapped[list["TestRun"]] = relationship(back_populates="experiment")
    findings: Mapped[list["Finding"]] = relationship(back_populates="experiment")


class TestRun(Base):
    __tablename__ = "test_runs"

    id: Mapped[int] = mapped_column(primary_key=True)
    experiment_id: Mapped[int] = mapped_column(ForeignKey("experiments.id", ondelete="CASCADE"))
    run_label: Mapped[str | None] = mapped_column(Text)
    fuel: Mapped[str | None] = mapped_column(Text)
    oxygen_percent: Mapped[float | None] = mapped_column(Float)
    pressure_kpa: Mapped[float | None] = mapped_column(Float)
    flow_velocity_cm_s: Mapped[float | None] = mapped_column(Float)
    gravity: Mapped[Gravity] = mapped_column(
        _pg_enum(Gravity, "gravity"), default=Gravity.microgravity
    )
    initial_diameter_mm: Mapped[float | None] = mapped_column(Float)
    outcome: Mapped[Outcome] = mapped_column(_pg_enum(Outcome, "outcome"), default=Outcome.unknown)
    burn_rate_k: Mapped[float | None] = mapped_column(Float)
    extra: Mapped[dict[str, Any]] = mapped_column(JSONB, default=dict)

    experiment: Mapped[Experiment] = relationship(back_populates="test_runs")


class Finding(Base):
    __tablename__ = "findings"

    id: Mapped[int] = mapped_column(primary_key=True)
    experiment_id: Mapped[int | None] = mapped_column(
        ForeignKey("experiments.id", ondelete="SET NULL")
    )
    statement: Mapped[str] = mapped_column(Text)
    relevance_moon: Mapped[float] = mapped_column(Float, default=0.0)
    relevance_mars: Mapped[float] = mapped_column(Float, default=0.0)
    confidence: Mapped[float] = mapped_column(Float, default=0.0)

    experiment: Mapped[Experiment | None] = relationship(back_populates="findings")
    sources: Mapped[list["FindingSource"]] = relationship(back_populates="finding")


class FindingSource(Base):
    __tablename__ = "finding_sources"

    finding_id: Mapped[int] = mapped_column(
        ForeignKey("findings.id", ondelete="CASCADE"), primary_key=True
    )
    document_id: Mapped[int] = mapped_column(
        ForeignKey("documents.id", ondelete="CASCADE"), primary_key=True
    )
    page: Mapped[int] = mapped_column(Integer, primary_key=True)

    finding: Mapped[Finding] = relationship(back_populates="sources")
    document: Mapped[Document] = relationship()


class AICache(Base):
    """Cached LLM output (e.g. comparison summaries), keyed by request + provider."""

    __tablename__ = "ai_cache"

    key: Mapped[str] = mapped_column(Text, primary_key=True)
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
